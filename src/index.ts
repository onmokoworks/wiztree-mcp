function textResult(text: string) {
  return { content: [{ type: "text" as const, text }] };
}

function jsonResult(value: unknown) {
  return textResult(JSON.stringify(value));
}

function parseBytes(value: unknown): number {
  if (typeof value === "number") return value;
  const cleaned = String(value ?? "").replace(/[^\d.-]/g, "");
  const parsed = Number(cleaned);
  return Number.isFinite(parsed) ? parsed : 0;
}

function parseCount(value: unknown): number | undefined {
  if (value === undefined || value === null || value === "") return undefined;
  const parsed = Number(String(value).replace(/[^\d.-]/g, ""));
  return Number.isFinite(parsed) ? parsed : undefined;
}

function formatBytes(bytes: number): string {
  const units = ["B", "KB", "MB", "GB", "TB", "PB"];
  let value = Math.abs(bytes);
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  const signed = bytes < 0 ? "-" : "";
  const decimals = unit === 0 ? 0 : value >= 100 ? 1 : 2;
  return `${signed}${value.toFixed(decimals)} ${units[unit]}`;
}

// --- CSV parsing (streaming + cache) ---------------------------------------

type ColumnMap = {
  path: number;
  size: number;
  allocated: number;
  modified: number;
  attributes: number;
  files: number;
  folders: number;
};

function resolveColumns(header: string[]): ColumnMap {
  const idx = (...names: string[]) =>
    header.findIndex((cell) => names.includes(cell.replace(/^\uFEFF/, "").trim()));
  return {
    path: idx("File Name", "ファイル名"),
    size: idx("Size", "サイズ"),
    allocated: idx("Allocated", "割り当て"),
    modified: idx("Modified", "更新日時"),
    attributes: idx("Attributes", "属性"),
    files: idx("Files", "ファイル数"),
    folders: idx("Folders", "フォルダー"),
  };
}

function findHeaderOffset(text: string): number {
  // Header may be quoted ("File Name",...) or bare (File Name,...), English or Japanese.
  const match = /(?:^|\n)"?(?:file name|ファイル名)"?\s*,/i.exec(text);
  if (!match) return -1;
  return match.index === 0 ? 0 : match.index + 1;
}

// Skips the WizTree preamble ("Generated by WizTree ...") before the header row.
function makePreambleSkipper(): Transform {
  const decoder = new StringDecoder("utf8");
  let buffer = "";
  let done = false;
  return new Transform({
    transform(chunk, _enc, cb) {
      if (done) {
        this.push(chunk);
        return cb();
      }
      buffer += decoder.write(chunk as Buffer);
      const stripped = buffer.replace(/^\uFEFF/, "");
      const offset = findHeaderOffset(stripped);
      if (offset >= 0) {
        done = true;
        this.push(Buffer.from(stripped.slice(offset), "utf8"));
        buffer = "";
      } else if (buffer.length > 2_000_000) {
        done = true;
        this.push(Buffer.from(stripped, "utf8"));
        buffer = "";
      }
      cb();
    },
    flush(cb) {
      if (!done) {
        buffer += decoder.end();
        const stripped = buffer.replace(/^\uFEFF/, "");
        const offset = findHeaderOffset(stripped);
        this.push(Buffer.from(offset >= 0 ? stripped.slice(offset) : stripped, "utf8"));
      }
      cb();
    },
  });
}

async function parseCsvStream(resolvedPath: string): Promise<WizTreeEntry[]> {
  const parser = parse({ relax_column_count: true, skip_empty_lines: true });
  const stream = createReadStream(resolvedPath);
  const skipper = makePreambleSkipper();
  stream.on("error", (error) => parser.destroy(error));
  skipper.on("error", (error) => parser.destroy(error));
  stream.pipe(skipper).pipe(parser);

  const entries: WizTreeEntry[] = [];
  let cols: ColumnMap | undefined;
  for await (const record of parser as AsyncIterable<string[]>) {
    if (!cols) {
      cols = resolveColumns(record);
      continue;
    }
    const path = (cols.path >= 0 ? String(record[cols.path] ?? "") : "").trim();
    if (!path) continue;

    const entry: WizTreeEntry = {
      path,
      size: parseBytes(cols.size >= 0 ? record[cols.size] : 0),
      allocated: parseBytes(cols.allocated >= 0 ? record[cols.allocated] : 0),
      isFolder: path.endsWith("\\") || path.endsWith("/"),
    };
    const modified = cols.modified >= 0 ? String(record[cols.modified] ?? "") : "";
    const attributes = cols.attributes >= 0 ? String(record[cols.attributes] ?? "") : "";
    const files = parseCount(cols.files >= 0 ? record[cols.files] : undefined);
    const folders = parseCount(cols.folders >= 0 ? record[cols.folders] : undefined);
    if (modified) entry.modified = modified;
    if (attributes) entry.attributes = attributes;
    if (files !== undefined) entry.files = files;
    if (folders !== undefined) entry.folders = folders;
    entries.push(entry);
  }
  return entries;
}

type CacheEntry = { key: string; mtimeMs: number; size: number; entries: WizTreeEntry[] };
const CACHE_LIMIT = 3;
const csvCache: CacheEntry[] = [];

async function readCsv(csvPath: string): Promise<WizTreeEntry[]> {
  const resolved = resolve(csvPath);
  if (!existsSync(resolved)) {
    throw new Error(
      `CSV not found: ${resolved}. Run scan_path first, or use list_snapshots to see available snapshots in ${exportDir}.`,
    );
  }
  const stats = await stat(resolved);
  const hitIndex = csvCache.findIndex(
    (entry) => entry.key === resolved && entry.mtimeMs === stats.mtimeMs && entry.size === stats.size,
  );
  if (hitIndex >= 0) {
    const [hit] = csvCache.splice(hitIndex, 1);
    csvCache.unshift(hit);
    return hit.entries;
  }
  const entries = await parseCsvStream(resolved);
  csvCache.unshift({ key: resolved, mtimeMs: stats.mtimeMs, size: stats.size, entries });
  while (csvCache.length > CACHE_LIMIT) csvCache.pop();
  return entries;
}

// --- Analysis helpers ------------------------------------------------------

function summarizeEntries(entries: WizTreeEntry[]) {
  const files = entries.filter((entry) => !entry.isFolder);
  const folders = entries.filter((entry) => entry.isFolder);
  const totalFileSize = files.reduce((sum, entry) => sum + entry.size, 0);
  const totalAllocated = files.reduce((sum, entry) => sum + entry.allocated, 0);
  const largestRoot = folders.reduce<WizTreeEntry | undefined>(
    (largest, entry) => (!largest || entry.size > largest.size ? entry : largest),
    undefined,
  );

  return {
    entries: entries.length,
    fileEntries: files.length,
    folderEntries: folders.length,
    totalFileSize,
    totalFileSizeHuman: formatBytes(totalFileSize),
    totalAllocated,
    totalAllocatedHuman: formatBytes(totalAllocated),
    largestFolder: largestRoot
      ? {
          path: largestRoot.path,
          size: largestRoot.size,
          sizeHuman: formatBytes(largestRoot.size),
          files: largestRoot.files,
          folders: largestRoot.folders,
        }
      : undefined,
  };
}

function selectTop(
  entries: WizTreeEntry[],
  kind: "files" | "folders" | "all",
  limit: number,
  by: "size" | "allocated",
): WizTreeEntry[] {
  return entries
    .filter((entry) => kind === "all" || (kind === "files" ? !entry.isFolder : entry.isFolder))
    .sort((a, b) => b[by] - a[by])
    .slice(0, limit);
}

function entryObject(entry: WizTreeEntry) {
  return {
    path: entry.path,
    kind: entry.isFolder ? "folder" : "file",
    size: entry.size,
    sizeHuman: formatBytes(entry.size),
    allocated: entry.allocated,
    allocatedHuman: formatBytes(entry.allocated),
    modified: entry.modified,
    files: entry.files,
    folders: entry.folders,
  };
}

// Compact tab-separated table to keep token counts low for list outputs.
function tableResult(header: string[], rows: string[][], preamble?: string) {
  const lines = [header.join("\t"), ...rows.map((row) => row.join("\t"))];
  const text = (preamble ? `${preamble}\n` : "") + lines.join("\n");
  return textResult(text);
}

function entriesTable(entries: WizTreeEntry[], preamble?: string) {
  return tableResult(
    ["sizeHuman", "kind", "path"],
    entries.map((entry) => [formatBytes(entry.size), entry.isFolder ? "folder" : "file", entry.path]),
    preamble,
  );
}

function extensionOf(entry: WizTreeEntry): string {
  const extension = extname(entry.path).toLowerCase();
  return extension || "[no extension]";
}

function normalizePath(path: string): string {
  return path.replace(/\//g, "\\").toLowerCase();
}

function commonPrefixLength(a: string, b: string): number {
  const max = Math.min(a.length, b.length);
  let i = 0;
  while (i < max && a[i] === b[i]) i += 1;
  return i;
}

// Direct children of folderPath, sorted by size descending.
function drillDown(entries: WizTreeEntry[], folderPath: string, limit: number) {
  let folderNorm = normalizePath(folderPath);
  if (!folderNorm.endsWith("\\")) folderNorm += "\\";

  const children: WizTreeEntry[] = [];
  let folderExists = false;
  for (const entry of entries) {
    const entryNorm = normalizePath(entry.path);
    if (entryNorm === folderNorm) {
      folderExists = true;
      continue;
    }
    if (!entryNorm.startsWith(folderNorm)) continue;
    folderExists = true;
    const remainder = entryNorm.slice(folderNorm.length).replace(/\\$/, "");
    if (remainder && !remainder.includes("\\")) children.push(entry);
  }

  if (!folderExists) {
    const suggestions = entries
      .filter((entry) => entry.isFolder)
      .map((entry) => ({ path: entry.path, score: commonPrefixLength(normalizePath(entry.path), folderNorm) }))
      .sort((a, b) => b.score - a.score)
      .slice(0, 5)
      .filter((candidate) => candidate.score > 0)
      .map((candidate) => candidate.path);
    return { found: false as const, suggestions };
  }

  const sorted = children.sort((a, b) => b.size - a.size).slice(0, limit);
  return { found: true as const, children: sorted };
}

function globToRegExp(query: string): RegExp {
  const escaped = query.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*").replace(/\?/g, ".");
  return new RegExp(escaped, "i");
}

function searchEntries(
  entries: WizTreeEntry[],
  query: string,
  kind: "files" | "folders" | "all",
  limit: number,
) {
  const useGlob = query.includes("*") || query.includes("?");
  const regex = useGlob ? globToRegExp(query) : undefined;
  const needle = query.toLowerCase();
  const matcher = (path: string) => (regex ? regex.test(path) : path.toLowerCase().includes(needle));

  let totalSize = 0;
  let totalCount = 0;
  const matches: WizTreeEntry[] = [];
  for (const entry of entries) {
    if (kind !== "all" && (kind === "files" ? entry.isFolder : !entry.isFolder)) continue;
    if (!matcher(entry.path)) continue;
    totalSize += entry.size;
    totalCount += 1;
    matches.push(entry);
  }
  matches.sort((a, b) => b.size - a.size);
  return { rows: matches.slice(0, limit), totalSize, totalCount };
}

function parseModified(value: string): number | undefined {
  const parsed = Date.parse(value);
  if (!Number.isNaN(parsed)) return parsed;
  const match = value.match(/(\d{4})\/(\d{1,2})\/(\d{1,2})(?:[ T](\d{1,2}):(\d{2})(?::(\d{2}))?)?/);
  if (match) {
    const date = new Date(
      Number(match[1]),
      Number(match[2]) - 1,
      Number(match[3]),
      Number(match[4] ?? 0),
      Number(match[5] ?? 0),
      Number(match[6] ?? 0),
    );
    const time = date.getTime();
    return Number.isNaN(time) ? undefined : time;
  }
  return undefined;
}

function oldLargeFiles(
  entries: WizTreeEntry[],
  olderThanDays: number,
  minSizeBytes: number,
  limit: number,
  now: number = Date.now(),
) {
  const cutoff = now - olderThanDays * 24 * 60 * 60 * 1000;
  const matches: { entry: WizTreeEntry; modifiedMs: number }[] = [];
  for (const entry of entries) {
    if (entry.isFolder || entry.size < minSizeBytes || !entry.modified) continue;
    const modifiedMs = parseModified(entry.modified);
    if (modifiedMs === undefined || modifiedMs > cutoff) continue;
    matches.push({ entry, modifiedMs });
  }
  matches.sort((a, b) => b.entry.size - a.entry.size);
  return matches.slice(0, limit);
}

// --- WizTree executable ----------------------------------------------------

function findWizTreeCandidates(): string[] {
  const candidates = new Set<string>();
  const envPath = process.env.WIZTREE_PATH;
  if (envPath) candidates.add(envPath);

  const pathDirs = (process.env.PATH ?? "").split(";").filter(Boolean);
  for (const dir of pathDirs) {
    candidates.add(join(dir, "WizTree64.exe"));
    candidates.add(join(dir, "WizTree.exe"));
  }

  for (const root of [process.env.ProgramFiles, process.env["ProgramFiles(x86)"]].filter(Boolean) as string[]) {
    candidates.add(join(root, "WizTree", "WizTree64.exe"));
    candidates.add(join(root, "WizTree", "WizTree.exe"));
    candidates.add(join(root, "Antibody Software", "WizTree", "WizTree64.exe"));
    candidates.add(join(root, "Antibody Software", "WizTree", "WizTree.exe"));
  }

  candidates.add(join(projectRoot, "WizTree64.exe"));
  candidates.add(join(projectRoot, "WizTree.exe"));
  candidates.add(join(dirname(projectRoot), "WizTree", "WizTree64.exe"));
  candidates.add(join(dirname(projectRoot), "WizTree", "WizTree.exe"));

  return [...candidates];
}

function locateWizTree(explicitPath?: string): string | undefined {
  if (explicitPath && existsSync(explicitPath)) return explicitPath;
  return findWizTreeCandidates().find((candidate) => existsSync(candidate));
}

function safeName(input: string): string {
  return input.replace(/^[A-Za-z]:/, (drive) => drive.replace(":", "")).replace(/[\\/:*?"<>|\s]+/g, "_").replace(/^_+|_+$/g, "") || "scan";
}

async function runWizTree(args: string[], timeoutSeconds: number): Promise<{ stdout: string; stderr: string }> {
  return await new Promise((resolvePromise, reject) => {
    const child = spawn(args[0], args.slice(1), {
      windowsHide: true,
      stdio: ["ignore", "pipe", "pipe"],
    });

    let stdout = "";
    let stderr = "";
    const timeout = setTimeout(() => {
      // On Windows, kill the whole process tree; a plain kill can leave WizTree running.
      if (isWindows && child.pid) {
        try {
          spawn("taskkill", ["/pid", String(child.pid), "/t", "/f"], { windowsHide: true });
        } catch {
          child.kill();
        }
      } else {
        child.kill();
      }
      reject(new Error(`WizTree timed out after ${timeoutSeconds} seconds.`));
    }, timeoutSeconds * 1000);

    child.stdout?.on("data", (chunk) => {
      stdout += chunk.toString();
    });
    child.stderr?.on("data", (chunk) => {
      stderr += chunk.toString();
    });
    child.on("error", (error) => {
      clearTimeout(timeout);
      reject(error);
    });
    child.on("close", (code) => {
      clearTimeout(timeout);
      if (code === 0) {
        resolvePromise({ stdout, stderr });
      } else {
        reject(new Error(`WizTree exited with code ${code}.${stderr ? ` stderr: ${stderr}` : ""}`));
      }
    });
  });
}

async function imageContent(pngPath: string) {
  const data = await readFile(pngPath);
  return { type: "image" as const, data: data.toString("base64"), mimeType: "image/png" };
}

