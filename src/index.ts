server.registerTool(
  "list_snapshots",
  {
    title: "List Snapshots",
    description: "List WizTree CSV snapshots in the export directory, newest first.",
    inputSchema: {},
  },
  async () => {
    if (!existsSync(exportDir)) {
      return tableResult(["mtime", "sizeHuman", "path"], [], `No export directory yet: ${exportDir}`);
    }
    const names = await readdir(exportDir);
    const snapshots = [];
    for (const name of names) {
      if (!name.toLowerCase().endsWith(".csv")) continue;
      const full = join(exportDir, name);
      const stats = await stat(full);
      snapshots.push({ path: full, size: stats.size, mtimeMs: stats.mtimeMs });
    }
    snapshots.sort((a, b) => b.mtimeMs - a.mtimeMs);
    return tableResult(
      ["mtime", "sizeHuman", "path"],
      snapshots.map((snap) => [new Date(snap.mtimeMs).toISOString(), formatBytes(snap.size), snap.path]),
      `${snapshots.length} snapshot(s) in ${exportDir}`,
    );
  },
);

server.registerTool(
  "drill_down",
  {
    title: "Drill Down",
    description: "List the direct children (files and folders) of a folder within a WizTree snapshot, sorted by size.",
    inputSchema: {
      csvPath: z.string(),
      folderPath: z.string().describe('Folder path inside the snapshot, such as "C:\\Users\\me\\AppData".'),
      limit: z.number().int().positive().max(500).default(50),
    },
  },
  async (input) => {
    const entries = await readCsv(input.csvPath);
    const result = drillDown(entries, input.folderPath, input.limit);
    if (!result.found) {
      const hint = result.suggestions.length
        ? `\nClosest folders:\n${result.suggestions.join("\n")}`
        : "";
      return textResult(`Folder not found in snapshot: ${input.folderPath}${hint}`);
    }
    return entriesTable(result.children, `Direct children of ${input.folderPath} (${result.children.length} shown)`);
  },
);

