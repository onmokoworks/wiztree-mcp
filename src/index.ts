server.registerTool(
  "extension_summary",
  {
    title: "Extension Summary",
    description: "Aggregate file usage by extension from a WizTree CSV snapshot.",
    inputSchema: {
      csvPath: z.string(),
      limit: z.number().int().positive().max(500).default(100),
    },
  },
  async (input) => {
    const entries = (await readCsv(input.csvPath)).filter((entry) => !entry.isFolder);
    const byExtension = new Map<string, { extension: string; files: number; size: number; allocated: number }>();
    for (const entry of entries) {
      const extension = extensionOf(entry);
      const current = byExtension.get(extension) ?? { extension, files: 0, size: 0, allocated: 0 };
      current.files += 1;
      current.size += entry.size;
      current.allocated += entry.allocated;
      byExtension.set(extension, current);
    }

    const rows = [...byExtension.values()]
      .sort((a, b) => b.size - a.size)
      .slice(0, input.limit);
    return tableResult(
      ["sizeHuman", "files", "extension"],
      rows.map((row) => [formatBytes(row.size), String(row.files), row.extension]),
    );
  },
);

server.registerTool(
  "compare_csv",
  {
    title: "Compare CSV",
    description: "Compare two WizTree CSV snapshots by path and report the largest changes.",
    inputSchema: {
      beforeCsvPath: z.string(),
      afterCsvPath: z.string(),
      kind: z.enum(["files", "folders", "all"]).default("all"),
      limit: z.number().int().positive().max(500).default(50),
    },
  },
  async (input) => {
    const keep = (entry: WizTreeEntry) =>
      input.kind === "all" || (input.kind === "files" ? !entry.isFolder : entry.isFolder);
    const before = (await readCsv(input.beforeCsvPath)).filter(keep);
    const after = (await readCsv(input.afterCsvPath)).filter(keep);
    const beforeMap = new Map(before.map((entry) => [entry.path.toLowerCase(), entry]));
    const afterMap = new Map(after.map((entry) => [entry.path.toLowerCase(), entry]));
    const keys = new Set([...beforeMap.keys(), ...afterMap.keys()]);
    const changes = [...keys].map((key) => {
      const oldEntry = beforeMap.get(key);
      const newEntry = afterMap.get(key);
      const path = newEntry?.path ?? oldEntry?.path ?? key;
      const beforeSize = oldEntry?.size ?? 0;
      const afterSize = newEntry?.size ?? 0;
      const delta = afterSize - beforeSize;
      return {
        path,
        kind: (newEntry ?? oldEntry)?.isFolder ? "folder" : "file",
        delta,
        status: oldEntry && newEntry ? "changed" : oldEntry ? "removed" : "added",
      };
    });

    const growth = changes.filter((change) => change.delta > 0).sort((a, b) => b.delta - a.delta).slice(0, input.limit);
    const shrinkage = changes.filter((change) => change.delta < 0).sort((a, b) => a.delta - b.delta).slice(0, input.limit);
    const toRows = (list: typeof changes) => list.map((c) => [formatBytes(c.delta), c.status, c.kind, c.path]);
    const header = ["deltaHuman", "status", "kind", "path"];
    const growthText = ["# growth", header.join("\t"), ...toRows(growth).map((r) => r.join("\t"))].join("\n");
    const shrinkText = ["# shrinkage", header.join("\t"), ...toRows(shrinkage).map((r) => r.join("\t"))].join("\n");
    return textResult(`${growthText}\n\n${shrinkText}`);
  },
);

